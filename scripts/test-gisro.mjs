// node scripts/test-gisro.mjs — разбор названий и ФИО из ГИС РО
import { parseLocation, placeKey, isPerson, cleanText, cityBox, slugify } from "./gisro-lib.mjs";
let bad = 0;
const t = (name, cond, extra = "") => { if (!cond) bad++; console.log(cond ? "OK  " : "FAIL", name, extra); };
const p = (s) => { const r = parseLocation(s); return r && `${r.type}:${r.name}`; };

t("город", p("г. Таганрог") === "г:Таганрог" && p("г.Донецк") === "г:Донецк" && p("город Шахты") === "г:Шахты");
t("без префикса — город", p("Шахты") === "г:Шахты" && p("шахты") === "г:Шахты");
t("опечатка в падеже", p("г. Донецка") === "г:Донецк");
t("р.п. раньше п.", p("р.п. Шолоховский") === "рп:Шолоховский" && p("п. Синегорский") === "п:Синегорский");
t("посёлок: пос./п./без пробела/NBSP", p("пос. Привольный") === "п:Привольный" && p("п.Рассвет") === "п:Рассвет" && p("п. Чертково") === "п:Чертково");
t("станица во всех написаниях", p("ст. Багаевская") === "ст:Багаевская" && p("ст-ца Николаевская") === "ст:Николаевская" && p("станица Романовская") === "ст:Романовская");
t("село/хутор/слобода", p("с.Тарасово-Меловское") === "с:Тарасово-Меловское" && p("х.Морозов") === "х:Морозов" && p("хутор Лагутники") === "х:Лагутники" && p("сл. Кашары") === "сл:Кашары");
t("опечатка Екатеринока", p("с. Екатеринока") === "с:Екатериновка" && placeKey(parseLocation("с. Екатеринока")) === placeKey(parseLocation("с. Екатериновка")));
t("варианты одного места дают один ключ", placeKey(parseLocation("п.Рассвет")) === placeKey(parseLocation("п. Рассвет")));
t("ё и е не разделяют место", placeKey(parseLocation("х. Новосёловка")) === placeKey(parseLocation("х. Новоселовка")));
t("пустое", parseLocation("") === null && parseLocation(null) === null);
t("название на «Г» не принимается за префикс города", p("Гуково") === "г:Гуково");

t("ФИО скрываются", isPerson("Иванов Иван Иванович") && isPerson("Иванов И.И.") && isPerson("ТСЖ Марченко Анатолий Николаевич") && isPerson("ЖСК Шанденский Сергей Александрович") && isPerson("Иванов-Петров Иван Иванович"));
t("организации остаются", !isPerson('ООО "УК Любимый дом"') && !isPerson("МБОУ СОШ 15") && !isPerson("ТСЖ Восточный") && !isPerson("УК ООО «Универсал»"));
t("чистка текста", cleanText('ООО " УК Северная звезда" ') === 'ООО "УК Северная звезда"' && cleanText("ул. Ленина,  5") === "ул. Ленина, 5");

const box = cityBox([{ lat: 47.13, lng: 39.69 }, { lat: 47.16, lng: 39.77 }]);
t("границы: центр, запас и масштаб", box.center[0] === 39.73 && box.bbox[0] < 39.69 && box.bbox[2] > 39.77 && box.zoom === 13, JSON.stringify(box));
t("одна точка: запас не нулевой", (() => { const b = cityBox([{ lat: 47, lng: 40 }]); return b.bbox[2] - b.bbox[0] > 0.079 && b.zoom === 15; })());
t("слаг", slugify("Каменск-Шахтинский") === "kamensk-shahtinskiy");
if (bad) process.exitCode = 1;
